#!/usr/bin/env python3
"""Generate the table of target-SDK-gated compat changes that system_server would apply.

On Android, system_server's PlatformCompat decides per app which compat changes are disabled --
chiefly the ones gated on a target SDK the app does not reach -- and hands the list to the process
as AppBindData.disabledCompatChanges. Direct launch has no system_server, and it passed an empty
list, which enables every change for every app: an app targeting SDK 28 got the SDK 31
PendingIntent mutability rule and threw from its own service's onCreate (Termux).

AOSP compiles this information into /system/etc/compatconfig/*.xml with an annotation processor;
the board has no such file. This reads the same annotations straight from source:

  @ChangeId @EnabledSince(targetSdkVersion = X)   enabled when targetSdk >= X
  @ChangeId @EnabledAfter(targetSdkVersion = X)   enabled when targetSdk >  X
  @ChangeId @Disabled                             never enabled by default
  @ChangeId (no gate)                             always enabled -- nothing to record

and writes CompatChangeTable.java, which AppSchedulerBridge asks for the disabled set.

Usage: gen_compat_changes.py --source-root <android-source> --out <CompatChangeTable.java>
"""
import argparse
import re
from pathlib import Path

# Android 15's Build.VERSION_CODES. CUR_DEVELOPMENT is the in-development sentinel.
VERSION_CODES = {
    'BASE': 1, 'BASE_1_1': 2, 'CUPCAKE': 3, 'DONUT': 4, 'ECLAIR': 5, 'ECLAIR_0_1': 6,
    'ECLAIR_MR1': 7, 'FROYO': 8, 'GINGERBREAD': 9, 'GINGERBREAD_MR1': 10, 'HONEYCOMB': 11,
    'HONEYCOMB_MR1': 12, 'HONEYCOMB_MR2': 13, 'ICE_CREAM_SANDWICH': 14,
    'ICE_CREAM_SANDWICH_MR1': 15, 'JELLY_BEAN': 16, 'JELLY_BEAN_MR1': 17, 'JELLY_BEAN_MR2': 18,
    'KITKAT': 19, 'KITKAT_WATCH': 20, 'LOLLIPOP': 21, 'LOLLIPOP_MR1': 22, 'M': 23, 'N': 24,
    'N_MR1': 25, 'O': 26, 'O_MR1': 27, 'P': 28, 'Q': 29, 'R': 30, 'S': 31, 'S_V2': 32,
    'TIRAMISU': 33, 'UPSIDE_DOWN_CAKE': 34, 'VANILLA_ICE_CREAM': 35, 'CUR_DEVELOPMENT': 10000,
}

TREES = ['frameworks-base', 'libcore', 'providers-mediaprovider', 'platform-compat',
         'modules-bluetooth', 'modules-wifi', 'frameworks-opt-telephony', 'modules-permission',
         'modules-connectivity', 'icu']

# The annotations between @ChangeId and the constant, then the constant itself.
DECL = re.compile(r'@ChangeId\b(?P<annos>(?:\s*@[\w.]+(?:\s*\([^)]*\))?)*)\s*'
                  r'(?:(?:public|protected|private|static|final)\s+)*long\s+(?P<name>\w+)\s*=\s*'
                  r'(?P<id>\d+)L?\s*;', re.S)
GATE = re.compile(r'@(EnabledSince|EnabledAfter)\s*\(\s*targetSdkVersion\s*=\s*([\w.]+)\s*\)')
DISABLED = re.compile(r'@Disabled\b')
COMMENTS = re.compile(r'/\*.*?\*/|//[^\n]*', re.S)


def version(expr):
    if expr.isdigit():
        return int(expr)
    return VERSION_CODES[expr.rsplit('.', 1)[-1]]


def scan(root):
    """Return {id: (minTargetSdk, name, source)} for every gated change, and a list of skips."""
    table, skipped = {}, []
    for tree in TREES:
        base = root / tree
        if not base.is_dir():
            continue
        for path in sorted(base.rglob('*.java')):
            text = path.read_text(errors='replace')
            if '@ChangeId' not in text:
                continue
            code = COMMENTS.sub(' ', text)
            for m in DECL.finditer(code):
                annos, name, cid = m['annos'], m['name'], int(m['id'])
                where = '%s/%s' % (tree, path.relative_to(base))
                if DISABLED.search(annos):
                    minimum = 2**31 - 1
                else:
                    gate = GATE.search(annos)
                    if gate is None:
                        continue   # ungated: enabled for everyone, nothing to disable
                    try:
                        sdk = version(gate[2])
                    except KeyError:
                        skipped.append('%s %s: unknown target %s' % (where, name, gate[2]))
                        continue
                    minimum = sdk if gate[1] == 'EnabledSince' else sdk + 1
                if cid in table and table[cid][0] != minimum:
                    skipped.append('%s %s: id %d already gated at %d' % (where, name, cid, table[cid][0]))
                    continue
                table[cid] = (minimum, name, where)
    return table, skipped


def render(table):
    rows = sorted(table.items(), key=lambda kv: (kv[1][0], kv[0]))
    ids = ',\n'.join('        %dL /* %s */' % (cid, name) for cid, (_, name, _) in rows)
    mins = ', '.join(str(minimum) for _, (minimum, _, _) in rows)
    return '''// GENERATED by tools/gen_compat_changes.py from @ChangeId annotations in the Android source.
// Do not edit by hand; regenerate instead.
package adapter.activity;

/**
 * Target-SDK-gated compat changes, as system_server's PlatformCompat would apply them.
 *
 * An app gets {@link #disabledFor} as AppBindData.disabledCompatChanges. A change is disabled when
 * the app's target SDK is below its minimum; @Disabled changes have a minimum no app reaches.
 */
public final class CompatChangeTable {
    private CompatChangeTable() {}

    private static final long[] IDS = {
%s
    };

    /** Lowest target SDK at which each change in IDS is enabled. */
    private static final int[] MIN_TARGET_SDK = { %s };

    public static long[] disabledFor(int targetSdk) {
        int count = 0;
        for (int minimum : MIN_TARGET_SDK) if (targetSdk < minimum) count++;
        long[] disabled = new long[count];
        int next = 0;
        for (int i = 0; i < IDS.length; i++) if (targetSdk < MIN_TARGET_SDK[i]) disabled[next++] = IDS[i];
        java.util.Arrays.sort(disabled);
        return disabled;
    }

    public static int size() { return IDS.length; }
}
''' % (ids, mins)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--source-root', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    table, skipped = scan(args.source_root)
    if not table:
        raise SystemExit('no gated compat changes found under ' + str(args.source_root))
    args.out.write_text(render(table))
    for line in skipped:
        print('skipped: ' + line)
    by_min = {}
    for minimum, _, _ in table.values():
        by_min[minimum] = by_min.get(minimum, 0) + 1
    print('wrote %d gated changes to %s' % (len(table), args.out))
    for minimum in sorted(by_min):
        label = 'disabled' if minimum == 2**31 - 1 else 'targetSdk >= %d' % minimum
        print('  %-18s %d' % (label, by_min[minimum]))


if __name__ == '__main__':
    main()
