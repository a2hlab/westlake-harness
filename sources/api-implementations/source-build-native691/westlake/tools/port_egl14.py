#!/usr/bin/env python3
"""Derive framework/opengl-jni/oh_egl14.cpp, oh_egl15.cpp and oh_eglext.cpp from AOSP's
android_opengl_EGL14.cpp, android_opengl_EGL15.cpp and android_opengl_EGLExt.cpp.

The android.opengl.EGL14/EGL15/EGLExt bindings are plain EGL plus JNI. What reaches into
Android's private graphics stack is:

  includes                        android_view_Surface.h, android_graphics_SurfaceTexture.h,
                                  gui/Surface.h, gui/GLConsumer.h, ui/ANativeObjectBase.h
  EGL14.eglCreateWindowSurface    android_view_Surface_getNativeWindow() -> sp<ANativeWindow>
  EGL14.eglCreateWindowSurfaceTexture  SurfaceTexture_getProducer() -> new Surface(producer)

EGLExt's eglDupNativeFenceFDANDROID is not exported by OH's libEGL and is resolved through
eglGetProcAddress. The window comes from wl_window_from_surface (oh_surface_window.cpp), shared
with the EGL10 port; a SurfaceTexture's window comes from wl_window_from_surface_texture, as there. Everything else is kept
byte-for-byte so the port can be diffed against the AOSP files.

Usage: port_egl14.py <aosp frameworks-base/core/jni> <out dir>
"""
import os, re, sys

jni, out = sys.argv[1], sys.argv[2]

PRIVATE_INCLUDES = [
    '#include <android_runtime/android_view_Surface.h>\n',
    '#include <android_runtime/android_graphics_SurfaceTexture.h>\n',
    '#include <gui/Surface.h>\n',
    '#include <gui/GLConsumer.h>\n',
    '#include <ui/ANativeObjectBase.h>\n',
]
SHARED = ('// OH port: the OH window a Java Surface carries (oh_surface_window.cpp).\n'
          'extern "C" void* wl_window_from_surface(JNIEnv* env, jobject surface);\n'
          'extern "C" void* wl_window_from_surface_texture(JNIEnv* env, jobject surfaceTexture);\n')


def function_span(text, name):
    m = re.search(r'\nstatic jobject\n' + name + r'\n', text)
    if not m:
        raise SystemExit('function not found: ' + name)
    start = m.start() + 1
    depth, i = 0, text.index('{', start)
    while True:
        if text[i] == '{': depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0: return start, i + 1
        i += 1


def port(name, edit):
    src = open(os.path.join(jni, 'android_opengl_%s.cpp' % name)).read()
    for inc in PRIVATE_INCLUDES:
        src = src.replace(inc, '')
    anchor = '#include <EGL/egl.h>\n'
    if anchor not in src: raise SystemExit(name + ': EGL include not found')
    src = src.replace(anchor, anchor + SHARED, 1)
    src = edit(src)
    if 'android::sp<' in src or 'android_view_Surface' in src or 'SurfaceTexture_get' in src:
        raise SystemExit(name + ': Android-private graphics code left in the port')
    header = ('// GENERATED by tools/port_egl14.py from AOSP frameworks/base/core/jni/'
              'android_opengl_%s.cpp.\n// Only the private includes and the window-surface '
              'functions differ; see the script.\n' % name)
    path = os.path.join(out, 'oh_%s.cpp' % name.lower())
    open(path, 'w').write(header + src)
    print('wrote', path)


def egl14(src):
    start, end = function_span(src, 'android_eglCreateWindowSurface')
    fn = src[start:end]
    for old, new in [('    android::sp<ANativeWindow> window;\n', '    void* window = NULL;\n'),
                     ('    window = android::android_view_Surface_getNativeWindow(_env, win);\n',
                      '    window = wl_window_from_surface(_env, win);\n'),
                     ('(EGLNativeWindowType)window.get()', '(EGLNativeWindowType)window')]:
        if old not in fn: raise SystemExit('EGL14 eglCreateWindowSurface: not found: ' + old.strip())
        fn = fn.replace(old, new, 1)
    src = src[:start] + fn + src[end:]
    # The SurfaceTexture variant is the same function over the SurfaceTexture's own producer window.
    start, end = function_span(src, 'android_eglCreateWindowSurfaceTexture')
    signature = src[start:src.index('{', start)]
    body = fn[fn.index('{'):].replace('wl_window_from_surface(_env, win)',
                                       'wl_window_from_surface_texture(_env, win)', 1)
    return src[:start] + signature + body + src[end:]

def eglext(src):
    # OH's libEGL does not export this Android extension; ask the driver for it at run time, and
    # report no fence (EGL's own "none" value) where it has none.
    call = 'return eglDupNativeFenceFDANDROID('
    if call not in src: raise SystemExit('EGLExt: eglDupNativeFenceFDANDROID call not found')
    shim = ('\n// OH port: not exported by the OH libEGL; resolved from the driver when it is asked for.\n'
            'static EGLint wl_eglDupNativeFenceFDANDROID(EGLDisplay dpy, EGLSyncKHR sync) {\n'
            '    static PFNEGLDUPNATIVEFENCEFDANDROIDPROC fn = reinterpret_cast<PFNEGLDUPNATIVEFENCEFDANDROIDPROC>(\n'
            '            eglGetProcAddress("eglDupNativeFenceFDANDROID"));\n'
            '    return fn != nullptr ? fn(dpy, sync) : EGL_NO_NATIVE_FENCE_FD_ANDROID;\n'
            '}\n')
    anchor = '#include <EGL/eglext.h>\n'
    src = src.replace(anchor, anchor + shim, 1)
    return src.replace(call, 'return wl_eglDupNativeFenceFDANDROID(', 1)


port('EGL14', egl14)
port('EGL15', lambda s: s)
port('EGLExt', eglext)
