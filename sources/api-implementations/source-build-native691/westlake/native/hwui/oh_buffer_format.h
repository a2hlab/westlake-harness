#pragma once
#include "oh61_buffer_handle.h"
#include <android/hardware_buffer.h>
#include <native_buffer/native_buffer.h>

inline int westlakeAndroidBufferFormat(int host) {
    switch (host) {
        case NATIVEBUFFER_PIXEL_FMT_RGBA_8888: return AHARDWAREBUFFER_FORMAT_R8G8B8A8_UNORM;
        case NATIVEBUFFER_PIXEL_FMT_RGBX_8888: return AHARDWAREBUFFER_FORMAT_R8G8B8X8_UNORM;
        case NATIVEBUFFER_PIXEL_FMT_RGB_888: return AHARDWAREBUFFER_FORMAT_R8G8B8_UNORM;
        case NATIVEBUFFER_PIXEL_FMT_RGB_565: return AHARDWAREBUFFER_FORMAT_R5G6B5_UNORM;
        case NATIVEBUFFER_PIXEL_FMT_RGBA16_FLOAT: return AHARDWAREBUFFER_FORMAT_R16G16B16A16_FLOAT;
        case NATIVEBUFFER_PIXEL_FMT_RGBA_1010102: return AHARDWAREBUFFER_FORMAT_R10G10B10A2_UNORM;
        case NATIVEBUFFER_PIXEL_FMT_BLOB: return AHARDWAREBUFFER_FORMAT_BLOB;
        default: return 0;
    }
}
inline int westlakeHostBufferFormat(int android) {
    switch (android) {
        case AHARDWAREBUFFER_FORMAT_R8G8B8A8_UNORM: return NATIVEBUFFER_PIXEL_FMT_RGBA_8888;
        case AHARDWAREBUFFER_FORMAT_R8G8B8X8_UNORM: return NATIVEBUFFER_PIXEL_FMT_RGBX_8888;
        case AHARDWAREBUFFER_FORMAT_R8G8B8_UNORM: return NATIVEBUFFER_PIXEL_FMT_RGB_888;
        case AHARDWAREBUFFER_FORMAT_R5G6B5_UNORM: return NATIVEBUFFER_PIXEL_FMT_RGB_565;
        case AHARDWAREBUFFER_FORMAT_R16G16B16A16_FLOAT: return NATIVEBUFFER_PIXEL_FMT_RGBA16_FLOAT;
        case AHARDWAREBUFFER_FORMAT_R10G10B10A2_UNORM: return NATIVEBUFFER_PIXEL_FMT_RGBA_1010102;
        case AHARDWAREBUFFER_FORMAT_BLOB: return NATIVEBUFFER_PIXEL_FMT_BLOB;
        default: return -1;
    }
}
inline int westlakeBufferPixelBytes(int android) {
    switch (android) {
        case AHARDWAREBUFFER_FORMAT_R5G6B5_UNORM: return 2;
        case AHARDWAREBUFFER_FORMAT_R8G8B8_UNORM: return 3;
        case AHARDWAREBUFFER_FORMAT_R8G8B8A8_UNORM:
        case AHARDWAREBUFFER_FORMAT_R8G8B8X8_UNORM:
        case AHARDWAREBUFFER_FORMAT_R10G10B10A2_UNORM: return 4;
        case AHARDWAREBUFFER_FORMAT_R16G16B16A16_FLOAT: return 8;
        case AHARDWAREBUFFER_FORMAT_BLOB: return 1;
        default: return 0;
    }
}
inline uint64_t westlakeHostBufferUsage(uint64_t usage) {
    uint64_t result = NATIVEBUFFER_USAGE_MEM_DMA;
    if (usage & AHARDWAREBUFFER_USAGE_CPU_READ_MASK) result |= NATIVEBUFFER_USAGE_CPU_READ;
    if (usage & AHARDWAREBUFFER_USAGE_CPU_WRITE_MASK) result |= NATIVEBUFFER_USAGE_CPU_WRITE;
    if ((usage & AHARDWAREBUFFER_USAGE_CPU_READ_MASK) == AHARDWAREBUFFER_USAGE_CPU_READ_OFTEN)
        result |= NATIVEBUFFER_USAGE_CPU_READ_OFTEN;
    if (usage & AHARDWAREBUFFER_USAGE_GPU_SAMPLED_IMAGE) result |= NATIVEBUFFER_USAGE_HW_TEXTURE;
    if (usage & AHARDWAREBUFFER_USAGE_GPU_COLOR_OUTPUT) result |= NATIVEBUFFER_USAGE_HW_RENDER;
    return result;
}
inline uint64_t westlakeAndroidBufferUsage(uint64_t usage) {
    uint64_t result = 0;
    if (usage & NATIVEBUFFER_USAGE_CPU_READ)
        result |= (usage & NATIVEBUFFER_USAGE_CPU_READ_OFTEN) ?
                AHARDWAREBUFFER_USAGE_CPU_READ_OFTEN : AHARDWAREBUFFER_USAGE_CPU_READ_RARELY;
    if (usage & NATIVEBUFFER_USAGE_CPU_WRITE) result |= AHARDWAREBUFFER_USAGE_CPU_WRITE_OFTEN;
    if (usage & NATIVEBUFFER_USAGE_HW_TEXTURE) result |= AHARDWAREBUFFER_USAGE_GPU_SAMPLED_IMAGE;
    if (usage & NATIVEBUFFER_USAGE_HW_RENDER) result |= AHARDWAREBUFFER_USAGE_GPU_COLOR_OUTPUT;
    return result;
}
