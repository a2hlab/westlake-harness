#!/usr/bin/env python3
"""Generate forwarders for GL functions the Java bindings call but OH's libGLESv3 does not export.

OH ships libGLESv2/libGLESv3 and no libGLESv1_CM; the GLES 1 entry points exist only inside the GPU
driver. Extension functions (KHR/OES/EXT) are not exported by libGLESv3 either; the spec-correct way
to reach those is eglGetProcAddress. AOSP's GL10 and android.opengl.GLES10/11 bindings call them directly, so they need a
definition to link against. For every function declared in the GLES 1 headers that the board's
libGLESv3 does not export, this emits a forwarder with the exact prototype that resolves the real
function on first use -- eglGetProcAddress first, then the already-loaded driver -- and, if neither
has it, logs once and returns zero rather than jumping to null.

Usage: gen_gles1_forwarders.py <libGLESv3 exports file> <out.c> <header>...
"""
import re, sys
exports_file, out = sys.argv[1:3]; headers = sys.argv[3:]
exported = set(open(exports_file).read().split())
decl = re.compile(r'GL_API(?:CALL)?\s+([\w\s\*]+?)\s+GL_APIENTRY\s+(gl\w+)\s*\(([^;]*?)\)\s*;', re.S)
funcs = {}
for header in headers:
    for ret, name, args in decl.findall(open(header).read()):
        if name not in exported:
            funcs[name] = (' '.join(ret.split()), ' '.join(args.split()))
lines = ['// GENERATED by tools/gen_gles1_forwarders.py. Do not edit.',
         '#include <GLES/gl.h>', '#include <GLES/glext.h>', '#include <GLES2/gl2.h>', '#include <GLES2/gl2ext.h>', '#include <EGL/egl.h>',
         '#include <dlfcn.h>', '#include <stdio.h>', '',
         'static void *westlake_gles1_resolve(const char *name) {',
         '    void *fn = (void *) eglGetProcAddress(name);',
         '    if (fn == NULL) {',
         '        static void *driver;',
         '        if (driver == NULL) driver = dlopen("libGLES_mali.z.so", RTLD_NOW | RTLD_NOLOAD);',
         '        if (driver != NULL) fn = dlsym(driver, name);',
         '    }',
         '    if (fn == NULL) fprintf(stderr, "[WESTLAKE-GLES1] %s unavailable on this driver\\n", name);',
         '    return fn;',
         '}', '']
for name, (ret, args) in sorted(funcs.items()):
    params = [] if args in ('void', '') else [a.strip() for a in args.split(',')]
    names = [re.findall(r'(\w+)\s*(?:\[\s*\d*\s*\])?$', p)[0] for p in params]
    call = ', '.join(names)
    ftype = f'{ret} (GL_APIENTRY *)({args or "void"})'
    body = (f'    static {ret} (GL_APIENTRY *real)({args or "void"});\n'
            f'    if (real == NULL) real = ({ftype}) westlake_gles1_resolve("{name}");\n')
    if ret == 'void':
        body += f'    if (real != NULL) real({call});\n'
    else:
        body += f'    return real != NULL ? real({call}) : ({ret}) 0;\n'
    lines.append(f'GL_API {ret} GL_APIENTRY {name}({args or "void"}) {{\n{body}}}\n')
open(out, 'w').write('\n'.join(lines))
print(f'{len(funcs)} forwarders written to {out}')
