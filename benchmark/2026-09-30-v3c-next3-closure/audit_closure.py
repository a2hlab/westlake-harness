#!/usr/bin/env python3
"""Offline per-app DT_NEEDED graph and generated OH6.1 namespace policy."""
import argparse, hashlib, json, re, subprocess
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
p = argparse.ArgumentParser()
p.add_argument('--app-inputs', type=Path, required=True)
p.add_argument('--readelf', required=True)
p.add_argument('--package', type=Path, default=Path('/Users/zhaoyue/orca/workspaces/westlake-generation-v3c-next2-audio-anl'))
a = p.parse_args()
pool = REPO / 'bms/src/.work/b68-generation/platform-pool'
# Use the exact candidate Android/root files before platform dependencies.
runtime = [a.package / 'payload/android/lib64', a.package / 'payload/route', a.package / 'payload/zigzag']
platform = [pool / ('system/lib64' + suffix) for suffix in ['', '/platformsdk', '/chipset-sdk', '/chipset-sdk-sp', '/ndk']]
index = {}
for root in reversed(runtime + platform):
    for f in sorted(root.glob('*')):
        if f.is_file() and '.so' in f.name:
            index[f.name] = f
cache = {}
def elf(f):
    key = str(f)
    if key not in cache:
        if f.read_bytes()[:4] != b'\x7fELF':
            raise ValueError('not ELF: ' + key)
        text = subprocess.check_output([a.readelf, '-d', str(f)], text=True)
        cache[key] = {'path': key, 'sha256': hashlib.sha256(f.read_bytes()).hexdigest(),
                      'needed': re.findall(r'\(NEEDED\).*\[(.*?)\]', text),
                      'soname': re.findall(r'\(SONAME\).*\[(.*?)\]', text)}
    return cache[key]
keys = ['anki', 'fd-netguard', 'fd-auxio', 'vlc', 'fd-droidify', 'fd-noice', 'wikipedia', 'fd-android', 'ooniprobe', 'localsend']
runtime_seeds = sorted({f for root in runtime for f in root.glob('*') if f.is_file() and '.so' in f.name})
# Retain the explicitly requested NDK entry points from next2, including dlopen-only names.
previous = json.loads((ROOT.parent / '2026-09-30-v3c-next2-ndk/needed-closure.json').read_text())['ndk_sonames']
runtime_seeds = sorted(set(runtime_seeds + [index[name] for name in previous]))
contexts = {'runtime': {}}
for key in keys:
    directory = a.app_inputs / key / 'lib/arm64-v8a'
    files = {f.name: f for f in directory.glob('*.so') if f.is_file()}
    contexts[key] = files
edges, unresolved, seen, shared, roots = [], [], set(), set(), set()
context_counts = {}
for context, own in contexts.items():
    seeds = list(own.values()) if own else (runtime_seeds if context == 'runtime' else [])
    context_counts[context] = len(seeds)
    queue = deque(seeds)
    while queue:
        f = queue.popleft(); identity = (context, str(f))
        if identity in seen: continue
        seen.add(identity)
        row = elf(f)
        try:
            rel = f.relative_to(pool)
        except ValueError:
            rel = None
        if rel is not None:
            names = [f.name] + row['soname']
            for name in names:
                if '/' in name or ':' in name or '..' in name: raise ValueError(name)
                shared.add(name)
            roots.add('/' + str(rel.parent))
        for name in row['needed']:
            target = own.get(name) or index.get(name)
            edges.append({'context': context, 'source': str(f), 'needed': name, 'resolved': str(target) if target else None})
            if target: queue.append(target)
            else: unresolved.append({'context': context, 'source': str(f), 'needed': name})
# Preserve B87 runtime compatibility supply alongside the complete OH names.
shared.update(['libbionic_compat.so', 'libc++.so', 'libhilog.so', 'libbegetutil.z.so', 'libsec_shared.z.so', 'libconfigpolicy_util.z.so', 'libsystemparam.z.so', 'libc.so'])
ordered_roots = [str('/' + str(r.relative_to(pool))) for r in platform if '/' + str(r.relative_to(pool)) in roots]
result = {'package': str(a.package), 'context_seed_counts': context_counts, 'elf_files': len(cache), 'context_nodes': len(seen), 'shared_names': sorted(shared), 'dependency_roots': ordered_roots, 'unresolved': unresolved, 'files': cache, 'edges': edges, 'scope': 'DT_NEEDED with per-app sibling resolution; dlopen and driver runtime are device checks'}
(ROOT / 'closure.json').write_text(json.dumps(result, indent=2) + '\n')
header = ['/* Generated by benchmark/2026-09-30-v3c-next3-closure/audit_closure.py. */', '#ifndef WESTLAKE_OH_DEPENDENCIES_H', '#define WESTLAKE_OH_DEPENDENCIES_H', 'static const char kOhDependencyRoots[] = ' + json.dumps(':'.join(ordered_roots)) + ';', 'static const char kOhSharedDependencies[] =']
for i, name in enumerate(sorted(shared)):
    header.append('    ' + json.dumps((':' if i else '') + name))
header += ['    ;', '#endif', '']
(REPO / 'bms/src/adapter/framework/app-native-loader/src/oh_system_dependencies.h').write_text('\n'.join(header))
(ROOT / 'summary.json').write_text(json.dumps({k:result[k] for k in ['context_seed_counts','elf_files','context_nodes','dependency_roots','shared_names','unresolved']},indent=2)+'\n')
print(json.dumps({'elf_files':len(cache),'shared_names':len(shared),'shared_bytes':len(':'.join(sorted(shared))),'roots':ordered_roots,'unresolved_names':sorted({x['needed'] for x in unresolved}),'seeds':context_counts},indent=2))
