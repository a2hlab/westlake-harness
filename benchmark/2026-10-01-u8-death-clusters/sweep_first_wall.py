#!/usr/bin/env python3
"""First wall of every U8 dead key, from the signed sweep run only, joined with the U9 prediction.

    python3 benchmark/2026-10-01-u8-death-clusters/sweep_first_wall.py [--out-dir DIR]

Why (2026-10-01 18:06): a re-clustering over all index rows mixed smoke and repeat runs into the sweep (98 rows for
67 non-lit keys) and clustered white windows -- alive, so without a death cause -- by "cause", which made 55% of the
rows look causeless. Here: one row per key (the u8-sweep run the outer loop signed), dead keys only, family from the
run_index cause (Java exception class) or first_fatal (native abort / signal / exit), and the U9 v4 prediction per key
so "still dead after U9" is the next batch's candidate list.
"""
import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'scripts/lab'))
import lab_paths  # noqa: E402

SIGNOFF = REPO / 'benchmark/2026-10-01-u8-sweep/outer-signoff.json'
PREDICT = REPO / 'benchmark/2026-10-01-u9-prediction/predictions-v4.csv'
U8 = 'e953c0921536'


def family(row):
    cause, fatal = row.get('cause') or '', row.get('first_fatal') or ''
    m = re.search(r'([\w.$]+(?:Exception|Error))', cause)
    if m:
        return 'java:' + m.group(1).split('.')[-1]
    if 'JNI DETECTED' in fatal:
        return 'native:jni-abort'
    if re.search(r'Fatal signal|Reason:Signal|exit with signal', fatal):
        return 'native:signal'
    if 'System.exit' in fatal:
        return 'exit-without-java-chain'
    return 'other-fatal' if fatal else 'no-fatal'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out-dir', type=Path, default=Path(__file__).resolve().parent)
    args = ap.parse_args(argv)
    keys = json.loads(SIGNOFF.read_text())['keys']
    verdict = {e['key']: e['verdict'] for e in keys} if isinstance(keys, list) else {k: v['verdict'] for k, v in keys.items()}
    pred = {r['key']: r for r in csv.DictReader(open(PREDICT))}
    sweep = {}
    for line in open(lab_paths.inputs() / 'run-index/index.jsonl'):
        r = json.loads(line)
        if r.get('runtime_fp') == U8 and 'u8-sweep' in r['run']:
            sweep.setdefault(r['key'], r)
    rows = []
    for key, v in sorted(verdict.items()):
        if v != 'dead':
            continue
        r = sweep.get(key)
        if r is None:
            raise SystemExit(f'no u8-sweep index row for {key}')
        p = pred.get(key, {})
        rows.append({'key': key, 'family': family(r), 'cause': (r.get('cause') or '')[:200],
                     'first_fatal': (r.get('first_fatal') or '')[:200], 'u9_prediction': p.get('prediction', ''),
                     'u9_reason': p.get('reason', ''), 'run': r['run']})
    fams = defaultdict(list)
    for r in rows:
        fams[r['family']].append(r)
    still = [r for r in rows if r['u9_prediction'] not in ('lit', 'lit?', 'alive-white-window')]
    (args.out_dir / 'first-wall.json').write_text(json.dumps(rows, indent=1, ensure_ascii=False))
    lines = ['# U8 dead keys: first wall from the signed sweep run, with the U9 v4 prediction', '',
             f'{len(rows)} dead keys (outer-signoff.json), one u8-sweep row each; generated by `sweep_first_wall.py`.', '',
             '| family | dead | U9 predicts lit / lit? / white | still dead after U9 | keys still dead |', '|---|---|---|---|---|']
    for f, rs in sorted(fams.items(), key=lambda kv: -len(kv[1])):
        moved = [r for r in rs if r['u9_prediction'] in ('lit', 'lit?', 'alive-white-window')]
        left = [r['key'].replace('cv2-', '') for r in rs if r not in moved]
        lines.append(f'| {f} | {len(rs)} | {len(moved)} | {len(left)} | {", ".join(left)} |')
    lines += ['', f'Still dead after U9 (the next batch picks from these): **{len(still)}** keys.', '']
    (args.out_dir / 'first-wall.md').write_text('\n'.join(lines))
    print(f'{len(rows)} dead keys, {len(fams)} families, {len(still)} still dead after U9 -> {args.out_dir}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
